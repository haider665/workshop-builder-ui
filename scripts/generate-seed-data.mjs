/**
 * Seed data generator: Reads CSV files and generates TypeScript seed data.
 * Run: node scripts/generate-seed-data.mjs
 * Output: src/store/seedData.ts
 */
import { readFileSync, writeFileSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')

// ── Parse CSV ─────────────────────────────────────────────────────────────────
function parseCSV(text) {
  const lines = text.replace(/\r/g, '').split('\n').filter(Boolean)
  const headers = lines[0].split(',')
  return lines.slice(1).map((line) => {
    const vals = line.split(',')
    const row = {}
    headers.forEach((h, i) => {
      row[h.trim()] = (vals[i] ?? '').trim()
    })
    return row
  })
}

// ── 1. Concern Codes ──────────────────────────────────────────────────────────
const concernCSV = readFileSync(resolve(root, 'instructions/Customer_Concern_Codes_0526.csv'), 'utf-8')
const concernRows = parseCSV(concernCSV)

// Map unique categories → assign shops (all concerns go to the auto shop for now)
const concernCategories = [...new Set(concernRows.map((r) => r.CATEGORY))]
  .filter(Boolean)
  .sort()

const concernData = concernRows
  .filter((r) => r.CONCERN_CODE && r.CONCERN_DESCRIPTION)
  .map((r) => ({
    code: r.CONCERN_CODE,
    category: r.CATEGORY || 'All other',
    name: r.CONCERN_DESCRIPTION,
    processTimeMins: parseInt(r.EST_DIAGNOSIS_MIN) || 30,
  }))

console.log(`Concerns: ${concernData.length} records, ${concernCategories.length} categories`)

// ── 2. Task Master (Services) ─────────────────────────────────────────────────
const taskCSV = readFileSync(resolve(root, 'instructions/Task_Master_Full.csv'), 'utf-8')
const taskRows = parseCSV(taskCSV)

// Map shop types
const shopTypeMap = { 'Mechanical': 'Auto', 'Paintshop': 'Paint', 'Bodyshop': 'Body' }

// Stage column names in order
const stageColumns = [
  'DISSASSEMBLY_STAGE',
  'BODY_REPAIR_STAGE',
  'PAINT_PREP_STAGE',
  'PAINT_SPRAY_STAGE',
  'PRE_ASSEMBLY_STAGE',
  'PAINT_CUTTING_STAGE',
  'FINAL_ASSEMBLY_STAGE',
  'POLISH_STAGE',
]

const stageNames = [
  'Disassembly',
  'Body Repair',
  'Paint Prep',
  'Paint Spray',
  'Pre-Assembly',
  'Paint Cutting',
  'Final Assembly',
  'Polish',
]

const serviceData = taskRows
  .filter((r) => r.ITEM_CODE)
  .map((r) => {
    const shopType = shopTypeMap[r['SHOP TYPE']] || 'Auto'
    const lts = parseInt(r.LTS) || 0
    const totalStageTime = parseInt(r.TOTAL_STAGE_TIME) || 0
    const processTimeMins = shopType === 'Auto' ? lts : totalStageTime

    // Build stages (only non-zero durations)
    const stages = []
    let order = 1
    for (let i = 0; i < stageColumns.length; i++) {
      const dur = parseInt(r[stageColumns[i]]) || 0
      if (dur > 0) {
        stages.push({ name: stageNames[i], order: order++, durationMins: dur })
      }
    }

    return {
      code: r.ITEM_CODE,
      name: r['TASK NAME'] || '',
      description: r['TASK DESCRIPTION'] || r['TASK NAME'] || '',
      shopType,
      vehicleSize: r.VEHICLE_SIZE || undefined,
      category: r.CATEGORY || '',
      section: r.SECTION || undefined,
      severity: r.SEVERITY || undefined,
      processTimeMins,
      mrp: parseInt(r.MRP) || 0,
      stages: stages.length > 0 ? stages : undefined,
    }
  })

console.log(`Services: ${serviceData.length} records`)

// ── 3. Generate TypeScript ────────────────────────────────────────────────────
const ts = `// AUTO-GENERATED — do not edit manually
// Generated by scripts/generate-seed-data.mjs
// Concerns: ${concernData.length} records, ${concernCategories.length} categories
// Services: ${serviceData.length} records

export type RawConcernSeed = {
  code: string
  category: string
  name: string
  processTimeMins: number
}

export type RawStageSeed = {
  name: string
  order: number
  durationMins: number
}

export type RawServiceSeed = {
  code: string
  name: string
  description: string
  shopType: 'Auto' | 'Paint' | 'Body'
  vehicleSize?: string
  category: string
  section?: string
  severity?: string
  processTimeMins: number
  mrp: number
  stages?: RawStageSeed[]
}

export const CONCERN_CATEGORIES: string[] = ${JSON.stringify(concernCategories, null, 2)}

export const RAW_CONCERNS: RawConcernSeed[] = ${JSON.stringify(concernData, null, 2)}

export const RAW_SERVICES: RawServiceSeed[] = ${JSON.stringify(serviceData, null, 2)}
`

const outPath = resolve(root, 'src/store/seedData.ts')
writeFileSync(outPath, ts, 'utf-8')
console.log(`Written to ${outPath} (${(ts.length / 1024).toFixed(0)} KB)`)
